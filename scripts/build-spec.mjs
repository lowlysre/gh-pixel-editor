// Renders site/spec/sprite-format.md into the site homepage (site/index.html).
// Handles only the Markdown the spec uses: headings, paragraphs, lists, tables,
// fenced code, inline code, bold, links and bare URLs.
// Usage: node scripts/build-spec.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "site", "spec", "sprite-format.md");
const OUT = join(root, "site", "index.html");

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const slug = (s) => s.toLowerCase().replace(/<[^>]+>/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// The Markdown lives in site/spec/, the page in site/; rebase relative links.
const href = (h) => (/^([a-z]+:|#|\/)/.test(h) ? h : `spec/${h}`);

function inline(text) {
  const code = [];
  let s = text.replace(/`([^`]+)`/g, (_, c) => `\u0000${code.push(c) - 1}\u0000`);
  s = esc(s)
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, h) => `<a href="${href(h)}">${t}</a>`)
    .replace(/(^|[\s(])(https?:\/\/[^\s<)]+)/g, '$1<a href="$2">$2</a>')
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${esc(code[i])}</code>`);
}

const cells = (line) => line.trim().replace(/^\||\|$/g, "").split("|").map((c) => c.trim());

export function renderMarkdown(md) {
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  const out = [];
  const toc = [];
  let title = "";
  for (let i = 0; i < lines.length; ) {
    const line = lines[i];
    if (!line.trim()) {
      i++;
    } else if (line.startsWith("```")) {
      const body = [];
      for (i++; i < lines.length && !lines[i].startsWith("```"); i++) body.push(lines[i]);
      i++;
      out.push(`<pre><code>${esc(body.join("\n"))}</code></pre>`);
    } else if (/^#{1,3} /.test(line)) {
      const level = line.match(/^#+/)[0].length;
      const html = inline(line.slice(level + 1));
      if (level === 1) {
        title = html;
        out.push(`<h1>${html}</h1>`);
      } else {
        const id = slug(html);
        if (level === 2) toc.push({ id, html });
        out.push(`<h${level} id="${id}"><a href="#${id}">${html}</a></h${level}>`);
      }
      i++;
    } else if (line.startsWith("|")) {
      const head = cells(line);
      const rows = [];
      for (i += 2; i < lines.length && lines[i].startsWith("|"); i++) rows.push(cells(lines[i]));
      const tr = (r, tag) => `<tr>${r.map((c) => `<${tag}>${inline(c)}</${tag}>`).join("")}</tr>`;
      out.push(`<table><thead>${tr(head, "th")}</thead><tbody>${rows.map((r) => tr(r, "td")).join("")}</tbody></table>`);
    } else if (/^(- |\d+\. )/.test(line)) {
      const tag = line.startsWith("- ") ? "ul" : "ol";
      const items = [];
      for (; i < lines.length && /^(- |\d+\. )/.test(lines[i]); i++) items.push(lines[i].replace(/^(- |\d+\. )/, ""));
      out.push(`<${tag}>${items.map((t) => `<li>${inline(t)}</li>`).join("")}</${tag}>`);
    } else {
      const para = [];
      for (; i < lines.length && lines[i].trim() && !/^(#|```|\||- |\d+\. )/.test(lines[i]); i++) para.push(lines[i].trim());
      out.push(`<p>${inline(para.join(" "))}</p>`);
    }
  }
  return { title, toc, body: out.join("\n") };
}

export function buildPage(md) {
  const { title, toc, body } = renderMarkdown(md);
  const plainTitle = title.replace(/<[^>]+>/g, "");
  return `<!doctype html>
<!-- Generated by scripts/build-spec.mjs from site/spec/sprite-format.md. Do not edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${plainTitle}</title>
<meta name="description" content="A JSON format for pixel-art sprites that render cleanly in GitHub Actions logs and 256-colour terminals, with a browser-based editor.">
<meta property="og:type" content="website">
<meta property="og:title" content="${plainTitle}">
<meta property="og:description" content="A JSON format for pixel-art sprites that render cleanly in GitHub Actions logs.">
<meta property="og:url" content="https://lowlysre.github.io/gh-pixel-editor/">
<meta name="theme-color" content="#0d1117">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="style.css">
</head>
<body class="doc">
<header>
  <a class="brand" href="./"><img src="favicon.svg" alt="" width="18" height="18"> Pixel sprite format</a>
  <nav aria-label="Site">
    <a href="./" aria-current="page">Spec</a>
    <a href="spec/sprite.schema.json">Schema</a>
    <a href="spec/examples/slime.json">Example</a>
    <a class="cta" href="editor.html">Open editor</a>
    <a href="https://github.com/lowlysre/gh-pixel-editor">GitHub</a>
  </nav>
</header>
<div class="docwrap">
<nav class="toc" aria-label="Contents">
<ul>
${toc.map((t) => `<li><a href="#${t.id}">${t.html.replace(/<\/?code>/g, "")}</a></li>`).join("\n")}
</ul>
</nav>
<main>
${body}
</main>
</div>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const page = buildPage(readFileSync(SRC, "utf8"));
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") !== page) {
      console.error("site/index.html is stale; run npm run build-spec");
      process.exit(1);
    }
  } else writeFileSync(OUT, page);
}
